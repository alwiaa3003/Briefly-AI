import { useEffect, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { BookOpenText, ClipboardList, Layers, MessageSquareText, NotebookPen } from 'lucide-react';
import SourceAsk from './SourceAsk';
import StudyNotesPanel from './StudyNotesPanel';
import QuizPanel from './QuizPanel';
import FlashcardsPanel from './FlashcardsPanel';
import { StyleSelect, StyledSummary } from './SummaryStylePicker';
import * as aiService from '../../services/aiService';
import { TabList } from '../common/Tabs';

export const WORKSPACE_TABS = [
  { id: 'summary', label: 'Summary', icon: BookOpenText },
  { id: 'ask', label: 'Ask AI', icon: MessageSquareText },
  { id: 'notes', label: 'Study notes', icon: NotebookPen },
  { id: 'quiz', label: 'Quiz', icon: ClipboardList },
  { id: 'flashcards', label: 'Flashcards', icon: Layers },
];

/** Tabs for a completed source: the summary (in any style), Ask AI and study tools. */
export default function SourceWorkspace({ source, summary }) {
  const [params, setParams] = useSearchParams();
  const tab = WORKSPACE_TABS.some((t) => t.id === params.get('tab')) ? params.get('tab') : 'summary';
  const [style, setStyle] = useState(params.get('style') || null);

  // The preferred summary style (Settings) is the default; "standard" until preferences load.
  useEffect(() => {
    if (style) return undefined;
    let cancelled = false;
    Promise.resolve()
      .then(() => aiService.getPreferences())
      .then((prefs) => !cancelled && setStyle(prefs?.summaryStyle || 'standard'))
      .catch(() => !cancelled && setStyle('standard'));
    return () => {
      cancelled = true;
    };
  }, [style]);

  function selectTab(id) {
    const next = new URLSearchParams(params);
    if (id === 'summary') next.delete('tab');
    else next.set('tab', id);
    setParams(next, { replace: true });
  }

  function selectStyle(id) {
    setStyle(id);
    const next = new URLSearchParams(params);
    if (id === 'standard') next.delete('style');
    else next.set('style', id);
    setParams(next, { replace: true });
  }

  const activeStyle = style || 'standard';

  return (
    <div>
      <TabList label="Source workspace" tabs={WORKSPACE_TABS} value={tab} onChange={selectTab} className="mb-8" />

      <div role="tabpanel" id={`panel-${tab}`} aria-labelledby={`tab-${tab}`}>
        {tab === 'summary' && (
          <div className="space-y-8">
            {/* Everything below is written by Briefly; the header above describes the source itself. */}
            <div className="flex flex-wrap items-center justify-between gap-3">
              <p className="flex items-center gap-2 text-xs text-stone-500">
                <span className="h-1.5 w-1.5 rounded-full bg-brand-500" aria-hidden="true" />
                <span>
                  <span className="font-medium text-stone-700">Generated by Briefly</span> from the source above. Check key details against the original.
                </span>
              </p>
              <StyleSelect value={activeStyle} onChange={selectStyle} />
            </div>
            {activeStyle === 'standard' ? summary : <StyledSummary source={source} style={activeStyle} />}
          </div>
        )}
        {tab === 'ask' && <SourceAsk source={source} />}
        {tab === 'notes' && <StudyNotesPanel source={source} />}
        {tab === 'quiz' && <QuizPanel source={source} />}
        {tab === 'flashcards' && <FlashcardsPanel source={source} />}
      </div>
    </div>
  );
}
