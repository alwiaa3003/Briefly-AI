import { useEffect, useMemo, useState } from 'react';
import { Copy, Search } from 'lucide-react';
import { Card, CardHeader } from '../common/Card';
import Button from '../common/Button';
import EmptyState from '../common/EmptyState';
import Input from '../common/Input';
import Spinner from '../common/Spinner';
import TimestampButton from './TimestampButton';
import { useToast } from '../../hooks/useToast';
import * as sourceService from '../../services/sourceService';
import { getErrorMessage } from '../../utils/errors';
import { formatTimestamp } from '../../utils/format';

function Highlight({ text, query }) {
  if (!query) return text;
  const parts = [];
  const lower = text.toLowerCase();
  const needle = query.toLowerCase();
  let index = 0;
  for (;;) {
    const found = lower.indexOf(needle, index);
    if (found === -1) break;
    if (found > index) parts.push(text.slice(index, found));
    parts.push(
      <mark key={found} className="rounded-sm bg-amber-100 px-0.5 text-stone-900">
        {text.slice(found, found + query.length)}
      </mark>
    );
    index = found + query.length;
  }
  parts.push(text.slice(index));
  return parts;
}

export function transcriptToText(segments) {
  return segments
    .map((s) => `[${formatTimestamp(s.start)}] ${s.speaker ? `${s.speaker}: ` : ''}${s.text}`)
    .join('\n');
}

/** Searchable, timestamped transcript. Loaded on demand (it can be long). */
export default function TranscriptViewer({ source, onSeek }) {
  const toast = useToast();
  const [transcript, setTranscript] = useState(null);
  const [error, setError] = useState(null);
  const [query, setQuery] = useState('');

  useEffect(() => {
    let cancelled = false;
    sourceService
      .getTranscript(source.id)
      .then((result) => !cancelled && setTranscript(result))
      .catch((err) => !cancelled && setError(err));
    return () => {
      cancelled = true;
    };
  }, [source.id]);

  const trimmed = query.trim();
  const visible = useMemo(() => {
    if (!transcript) return [];
    if (!trimmed) return transcript.segments;
    const needle = trimmed.toLowerCase();
    return transcript.segments.filter((s) => s.text.toLowerCase().includes(needle) || s.speaker?.toLowerCase().includes(needle));
  }, [transcript, trimmed]);

  async function copyTranscript() {
    try {
      await navigator.clipboard.writeText(transcriptToText(transcript.segments));
      toast.success('Transcript copied');
    } catch {
      toast.error('Could not copy', 'Your browser blocked clipboard access.');
    }
  }

  const origin =
    source.kind === 'youtube'
      ? "Generated by AI from the video's audio, not YouTube's captions, so it may contain mistakes."
      : 'Generated by AI from the audio, so it may contain mistakes.';

  return (
    <Card aria-labelledby="transcript-heading">
      <CardHeader
        title={<span id="transcript-heading">Transcript</span>}
        description={origin}
        action={
          transcript ? (
            <Button variant="secondary" size="sm" onClick={copyTranscript}>
              <Copy className="h-3.5 w-3.5" aria-hidden="true" />
              Copy
            </Button>
          ) : null
        }
      />
      {error ? (
        <EmptyState title="The transcript could not be loaded" description={getErrorMessage(error)} />
      ) : !transcript ? (
        <div className="flex items-center gap-2 px-5 py-6 text-sm text-stone-500">
          <Spinner size="sm" /> Loading transcript…
        </div>
      ) : (
        <div className="p-5">
          <div className="mb-4 flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
            <Input
              aria-label="Search transcript"
              type="search"
              placeholder="Search the transcript"
              leadingIcon={Search}
              value={query}
              onChange={(event) => setQuery(event.target.value)}
              className="sm:w-72"
            />
            <p className="text-xs text-stone-500" aria-live="polite">
              {trimmed
                ? `${visible.length} matching ${visible.length === 1 ? 'line' : 'lines'}`
                : `${transcript.segments.length} lines · ${transcript.wordCount.toLocaleString()} words`}
            </p>
          </div>
          {visible.length === 0 ? (
            <p className="py-6 text-center text-sm text-stone-500">No lines match “{trimmed}”.</p>
          ) : (
            <ol className="max-h-[32rem] space-y-1 overflow-y-auto pr-1" aria-label="Transcript lines">
              {visible.map((segment) => (
                <li key={`${segment.start}-${segment.text.slice(0, 20)}`} className="flex gap-3 rounded-lg px-2 py-1.5 hover:bg-stone-50">
                  <TimestampButton seconds={segment.start} onSeek={onSeek} className="mt-0.5" />
                  <p className="text-sm leading-6 text-stone-700">
                    {segment.speaker && <span className="mr-1.5 font-medium text-stone-900">{segment.speaker}:</span>}
                    <Highlight text={segment.text} query={trimmed} />
                  </p>
                </li>
              ))}
            </ol>
          )}
        </div>
      )}
    </Card>
  );
}
